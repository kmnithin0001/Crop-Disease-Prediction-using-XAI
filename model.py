import numpy as np
from PIL import Image

def load_and_preprocess_image(image_path, target_size=(224, 224)):

    try:
        # Load the image using PIL's Image
        img = Image.open(image_path)
        # Resize the image
        img = img.resize(target_size)
        # Convert the image to RGB mode if it's not already
        if img.mode != 'RGB':
            img = img.convert('RGB')
        # Convert the image to a NumPy array and normalize pixel values
        img_array = np.array(img) / 255.0

        # Add an extra dimension to represent the batch size (for Keras)
        img_array = np.expand_dims(img_array, axis=0)
        return img_array
    except (FileNotFoundError, PIL.UnidentifiedImageError, OSError) as e:
        print(f"Error loading or preprocessing image: {e}")
        return None

def predict_image_class(model, image_path, class_indices):

    preprocessed_img = load_and_preprocess_image(image_path)

    # Check if image loading was successful
    if preprocessed_img is None:
        return "Error: Image could not be loaded or preprocessed."

    predictions = model.predict(preprocessed_img)
    predicted_class_index = np.argmax(predictions, axis=1)[0]
    predicted_class_name = class_indices[predicted_class_index]
    return predicted_class_name

